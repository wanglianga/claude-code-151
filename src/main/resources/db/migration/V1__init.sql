-- 城市图书馆跨馆借还服务：初始 schema
-- 所有状态机字段使用 varchar + check 约束，便于阅读与迁移。

CREATE TABLE library (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(32)  NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    district        VARCHAR(64)  NOT NULL,
    remote          BOOLEAN      NOT NULL DEFAULT FALSE,   -- 远端分馆：调拨保护更严格
    temp_closed     BOOLEAN      NOT NULL DEFAULT FALSE,   -- 临时闭馆
    reopen_date     DATE,                                  -- 预计恢复开放日
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE book (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn            VARCHAR(20)  NOT NULL UNIQUE,
    title           VARCHAR(256) NOT NULL,
    author          VARCHAR(128) NOT NULL,
    publisher       VARCHAR(128),
    publish_year    INT,
    ebook_url       VARCHAR(512),                          -- 电子资源替代
    ebook_available BOOLEAN      NOT NULL DEFAULT FALSE,
    price           NUMERIC(10,2) NOT NULL DEFAULT 50.00,  -- 定价（遗失赔偿依据）
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE book_copy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id             BIGINT NOT NULL REFERENCES book(id),
    barcode             VARCHAR(32) NOT NULL UNIQUE,       -- 馆藏条码
    owning_library_id   BIGINT NOT NULL REFERENCES library(id),   -- 归属馆
    current_library_id  BIGINT NOT NULL REFERENCES library(id),   -- 当前实际所在馆
    status              VARCHAR(24) NOT NULL,
    condition_state     VARCHAR(24) NOT NULL DEFAULT 'GOOD',
    CONSTRAINT ck_copy_status CHECK (status IN (
        'AVAILABLE',        -- 在馆可借
        'HELD',             -- 已为某预约锁定
        'IN_TRANSIT',       -- 调拨在途
        'ON_LOAN',          -- 借出中
        'DAMAGED',          -- 污损/缺页，下架处理
        'LOST',             -- 遗失（物流丢包/读者遗失）
        'WITHDRAWN'         -- 注销
    )),
    CONSTRAINT ck_copy_condition CHECK (condition_state IN ('GOOD','WORN','DAMAGED','SEVERE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_copy_book ON book_copy(book_id);
CREATE INDEX idx_copy_status ON book_copy(status);

CREATE TABLE patron (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_no     VARCHAR(32) NOT NULL UNIQUE,
    name        VARCHAR(64) NOT NULL,
    email       VARCHAR(128),
    status      VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT ck_patron_status CHECK (status IN ('ACTIVE','BLOCKED')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 预约（排队）
CREATE TABLE hold (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id             BIGINT NOT NULL REFERENCES book(id),
    patron_id           BIGINT NOT NULL REFERENCES patron(id),
    pickup_library_id   BIGINT NOT NULL REFERENCES library(id),
    reserved_copy_id    BIGINT REFERENCES book_copy(id),   -- 锁定的条码（排队中可为空）
    status              VARCHAR(16) NOT NULL,
    queue_seq           BIGINT NOT NULL,                   -- 排队序号（按创建顺序）
    ready_at            TIMESTAMPTZ,                         -- 到馆可取时间
    expires_at          TIMESTAMPTZ,                         -- 取书截止时间
    fulfilled_loan_id   BIGINT,
    cancel_reason       VARCHAR(256),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancelled_at        TIMESTAMPTZ,
    CONSTRAINT ck_hold_status CHECK (status IN (
        'QUEUED',        -- 排队中（等待锁码/调拨）
        'READY',         -- 已到馆待取
        'FULFILLED',     -- 已借出
        'EXPIRED',       -- 超时未取，已释放
        'CANCELLED'      -- 读者取消 / 闭馆取消
    ))
);
CREATE INDEX idx_hold_book_status ON hold(book_id, status);
CREATE INDEX idx_hold_patron ON hold(patron_id);

-- 馆际调拨任务 / 物流批次
CREATE TABLE transfer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_no      VARCHAR(40) UNIQUE,                    -- 包裹编号（物流员取书时登记）
    copy_id         BIGINT NOT NULL REFERENCES book_copy(id),
    from_library_id BIGINT NOT NULL REFERENCES library(id),
    to_library_id   BIGINT NOT NULL REFERENCES library(id),
    hold_id         BIGINT REFERENCES hold(id),
    status          VARCHAR(16) NOT NULL,
    eta_date        DATE,                                  -- 预计到达日
    picked_at       TIMESTAMPTZ,                             -- 物流员取书时间
    arrived_at      TIMESTAMPTZ,                             -- 实际到馆时间
    lost_at         TIMESTAMPTZ,
    note            VARCHAR(256),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_transfer_status CHECK (status IN (
        'CREATED',     -- 调拨任务已生成，待出库
        'PICKED_UP',   -- 物流员已取书出库
        'ARRIVED',     -- 已到目的馆
        'LOST',        -- 物流丢包
        'CANCELLED'    -- 取消（预约取消且书尚未出库）
    ))
);
CREATE INDEX idx_transfer_status ON transfer(status);
CREATE INDEX idx_transfer_copy ON transfer(copy_id);

-- 借阅记录
CREATE TABLE loan (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patron_id             BIGINT NOT NULL REFERENCES patron(id),
    copy_id               BIGINT NOT NULL REFERENCES book_copy(id),
    checkout_library_id   BIGINT NOT NULL REFERENCES library(id),
    due_date              DATE NOT NULL,
    renewed_count         INT NOT NULL DEFAULT 0,
    status                VARCHAR(16) NOT NULL,
    returned_at           TIMESTAMPTZ,
    return_library_id     BIGINT REFERENCES library(id),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_loan_status CHECK (status IN ('ACTIVE','RETURNED','LOST'))
);
ALTER TABLE hold ADD CONSTRAINT fk_hold_loan FOREIGN KEY (fulfilled_loan_id) REFERENCES loan(id);
CREATE INDEX idx_loan_patron ON loan(patron_id);
CREATE INDEX idx_loan_copy ON loan(copy_id);
CREATE INDEX idx_loan_due ON loan(due_date);

-- 罚款 / 赔偿 / 人工调整
CREATE TABLE fine (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patron_id   BIGINT NOT NULL REFERENCES patron(id),
    loan_id     BIGINT REFERENCES loan(id),
    type        VARCHAR(20) NOT NULL,
    amount      NUMERIC(10,2) NOT NULL,
    status      VARCHAR(12) NOT NULL DEFAULT 'OUTSTANDING',
    reason      VARCHAR(256) NOT NULL,
    rule_ref    VARCHAR(128),                 -- 规则依据（规则手册条目）
    manual      BOOLEAN NOT NULL DEFAULT FALSE,
    operator    VARCHAR(64),                  -- 人工调整的馆员
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    settled_at  TIMESTAMPTZ,
    CONSTRAINT ck_fine_type CHECK (type IN (
        'OVERDUE','DAMAGE','SEVERE_DAMAGE','LOST_COMPENSATION','MANUAL_ADJUSTMENT'
    )),
    CONSTRAINT ck_fine_status CHECK (status IN ('OUTSTANDING','PAID','WAIVED','ADJUSTED'))
);
CREATE INDEX idx_fine_patron ON fine(patron_id, status);

-- 异常事件（丢包 / 声称已还 / 污损 / 闭馆影响）
CREATE TABLE incident (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(24) NOT NULL,
    copy_id     BIGINT REFERENCES book_copy(id),
    loan_id     BIGINT REFERENCES loan(id),
    hold_id     BIGINT REFERENCES hold(id),
    description VARCHAR(512) NOT NULL,
    resolution  VARCHAR(512),
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    operator    VARCHAR(64),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ,
    CONSTRAINT ck_incident_type CHECK (type IN (
        'TRANSFER_LOST','RETURN_CLAIM','DAMAGE_REPORT','CLOSURE'
    )),
    CONSTRAINT ck_incident_status CHECK (status IN ('OPEN','RESOLVED'))
);

-- 读者通知
CREATE TABLE notice (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patron_id   BIGINT NOT NULL REFERENCES patron(id),
    loan_id     BIGINT REFERENCES loan(id),
    type        VARCHAR(24) NOT NULL,
    channel     VARCHAR(16) NOT NULL DEFAULT 'IN_APP',
    title       VARCHAR(128) NOT NULL,
    content     VARCHAR(512) NOT NULL,
    read_flag   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_notice_type CHECK (type IN (
        'READY_FOR_PICKUP','HOLD_EXPIRED','HOLD_CANCELLED',
        'DUE_REMINDER','OVERDUE','FINE_NOTICE','RETURN_CLAIM_RESULT','CLOSURE_NOTICE',
        'TRANSFER_ISSUE'
    ))
);
CREATE INDEX idx_notice_patron ON notice(patron_id, read_flag);

-- 审计日志：馆员人工调整必须留痕，可回看规则依据与影响
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(32) NOT NULL,
    entity_id   BIGINT,
    action      VARCHAR(64) NOT NULL,
    detail      VARCHAR(1024),
    rule_ref    VARCHAR(128),
    operator    VARCHAR(64) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_log(entity_type, entity_id);
