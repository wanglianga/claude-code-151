-- 城市图书馆跨馆调拨服务 核心 schema
-- 通用 SQL 子集，可同时在 PostgreSQL 与 H2(PostgreSQL 模式) 上由 Flyway 执行

CREATE TABLE libraries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(32)  NOT NULL UNIQUE,
    name             VARCHAR(128) NOT NULL,
    region           VARCHAR(64)  NOT NULL,
    x                DOUBLE PRECISION NOT NULL,
    y                DOUBLE PRECISION NOT NULL,
    temporary_closed BOOLEAN      NOT NULL DEFAULT FALSE,
    closed_until     TIMESTAMP,
    active           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE bibs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn            VARCHAR(20) NOT NULL UNIQUE,
    title           VARCHAR(256) NOT NULL,
    author          VARCHAR(128) NOT NULL,
    subject         VARCHAR(128),
    ebook_available BOOLEAN     NOT NULL DEFAULT FALSE,
    ebook_url       VARCHAR(512)
);

CREATE TABLE items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode             VARCHAR(32) NOT NULL UNIQUE,
    bib_id              BIGINT NOT NULL REFERENCES bibs(id),
    home_library_id     BIGINT NOT NULL REFERENCES libraries(id),
    current_library_id  BIGINT NOT NULL REFERENCES libraries(id),
    -- AVAILABLE 可借 / LOCKED 已被预约锁定待出库 / IN_TRANSIT 调拨中 /
    -- ON_HOLD 预约架待取 / CHECKED_OUT 借出 / LOST 丢失 / DAMAGED 污损待修 / WITHDRAWN 注销
    status              VARCHAR(16) NOT NULL,
    -- GOOD / FAIR / DAMAGED
    cond                VARCHAR(16) NOT NULL DEFAULT 'GOOD',
    missing_pages       BOOLEAN NOT NULL DEFAULT FALSE,
    accessories_note    VARCHAR(255)
);

CREATE TABLE readers (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_no VARCHAR(32) NOT NULL UNIQUE,
    name    VARCHAR(64) NOT NULL,
    email   VARCHAR(128),
    -- ACTIVE / SUSPENDED
    status  VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE policies (
    pk            VARCHAR(48) PRIMARY KEY,
    numeric_value DOUBLE PRECISION,
    text_value    VARCHAR(255),
    description   VARCHAR(512)
);

CREATE TABLE holds (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bib_id              BIGINT NOT NULL REFERENCES bibs(id),
    reader_id           BIGINT NOT NULL REFERENCES readers(id),
    pickup_library_id   BIGINT NOT NULL REFERENCES libraries(id),
    queue_position      INTEGER,
    -- QUEUED 排队中 / READY 到馆待取 / BORROWED 已借出 / CANCELLED 读者取消 /
    -- EXPIRED 超时未取 / LOST 调拨丢包终止
    status              VARCHAR(16) NOT NULL,
    item_id             BIGINT REFERENCES items(id),
    release_on_arrival  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMP NOT NULL,
    ready_at            TIMESTAMP,
    expires_at          TIMESTAMP,
    cancelled_at        TIMESTAMP
);
CREATE INDEX idx_holds_bib_status ON holds(bib_id, status, queue_position);
CREATE INDEX idx_holds_reader ON holds(reader_id, status);

CREATE TABLE transfer_batches (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no   VARCHAR(32) NOT NULL UNIQUE,
    staff_name VARCHAR(64),
    -- OPEN / CLOSED
    status     VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP NOT NULL,
    closed_at  TIMESTAMP
);

CREATE TABLE transfer_tasks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id            BIGINT REFERENCES holds(id),
    item_id            BIGINT NOT NULL REFERENCES items(id),
    from_library_id    BIGINT NOT NULL REFERENCES libraries(id),
    to_library_id      BIGINT NOT NULL REFERENCES libraries(id),
    batch_id           BIGINT REFERENCES transfer_batches(id),
    package_no         VARCHAR(48),
    -- CREATED 待取 / PICKED_UP 已出库 / ARRIVED 已到馆 / LOST 丢包
    status             VARCHAR(16) NOT NULL,
    release_on_arrival BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP NOT NULL,
    picked_at          TIMESTAMP,
    eta                TIMESTAMP,
    arrived_at         TIMESTAMP
);
CREATE INDEX idx_tasks_status ON transfer_tasks(status);
CREATE INDEX idx_tasks_batch ON transfer_tasks(batch_id);
CREATE INDEX idx_tasks_item ON transfer_tasks(item_id);

CREATE TABLE loans (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id            BIGINT NOT NULL REFERENCES readers(id),
    item_id              BIGINT NOT NULL REFERENCES items(id),
    checkout_library_id  BIGINT NOT NULL REFERENCES libraries(id),
    checked_out_at       TIMESTAMP NOT NULL,
    due_date             TIMESTAMP NOT NULL,
    renew_count          INTEGER NOT NULL DEFAULT 0,
    -- ACTIVE 借阅中 / RETURNED 已还 / CLAIMED_RETURNED 读者声称已还 / LOST 确认丢失
    status               VARCHAR(20) NOT NULL,
    returned_at          TIMESTAMP,
    returned_library_id  BIGINT REFERENCES libraries(id),
    condition_note       VARCHAR(255)
);
CREATE INDEX idx_loans_reader ON loans(reader_id, status);
CREATE INDEX idx_loans_item ON loans(item_id, status);
CREATE INDEX idx_loans_due ON loans(due_date, status);

CREATE TABLE fines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id   BIGINT REFERENCES readers(id),
    loan_id     BIGINT REFERENCES loans(id),
    task_id     BIGINT REFERENCES transfer_tasks(id),
    -- OVERDUE 逾期 / DAMAGE 污损 / MISSING_PAGES 缺页 / ACCESSORY 缺附件 /
    -- LOST 赔书 / LOGISTICS_LOSS 物流丢包赔偿 / MANUAL 人工录入
    type        VARCHAR(20) NOT NULL,
    -- READER 读者承担 / LIBRARY 馆方承担 / LOGISTICS 物流赔偿
    charged_to  VARCHAR(16) NOT NULL,
    amount      NUMERIC(10,2) NOT NULL,
    -- OPEN 待缴 / PAID 已缴 / WAIVED 已豁免 / REDUCED 已调减
    status      VARCHAR(16) NOT NULL,
    reason      VARCHAR(512),
    rule_basis  VARCHAR(512),
    created_at  TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP
);
CREATE INDEX idx_fines_reader ON fines(reader_id, status);

CREATE TABLE fine_adjustments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fine_id     BIGINT NOT NULL REFERENCES fines(id),
    staff       VARCHAR(64) NOT NULL,
    -- REDUCE 调减 / WAIVE 豁免
    action      VARCHAR(16) NOT NULL,
    old_amount  NUMERIC(10,2) NOT NULL,
    new_amount  NUMERIC(10,2) NOT NULL,
    reason      VARCHAR(512) NOT NULL,
    rule_basis  VARCHAR(512),
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE claims (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id     BIGINT NOT NULL REFERENCES loans(id),
    reader_id   BIGINT NOT NULL REFERENCES readers(id),
    -- OPEN / FOUND 找到已入库 / NOT_FOUND 确认丢失 / WAIVED 馆方豁免
    status      VARCHAR(16) NOT NULL,
    note        VARCHAR(512),
    staff       VARCHAR(64),
    created_at  TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id  BIGINT NOT NULL REFERENCES readers(id),
    -- READY 到馆取书 / HOLD_EXPIRED 预约超时 / DUE_REMINDER 到期提醒 /
    -- OVERDUE 逾期 / CANCEL 预约取消 / CLAIM 声称已还受理
    type       VARCHAR(24) NOT NULL,
    title      VARCHAR(128) NOT NULL,
    message    VARCHAR(1024) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    read_at    TIMESTAMP
);
CREATE INDEX idx_notifications_reader ON notifications(reader_id, created_at);
